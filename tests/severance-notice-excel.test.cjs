const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const JSZip=require('../vendor/jszip.min.js');
const NoticeExcel=require('../notice-excel.js');

const outputDir=path.resolve(__dirname,'..','..','tmp','severance-notice-excel');
const outputPath=path.join(outputDir,'王小明-資遣通知書.xlsx');
const model={companyName:'搜博科技股份有限公司',employeeName:'王小明',employeeId:'A123456789',employeeAddress:'新北市中和區中正路866號17樓',employeePhone:'0912-345-678',department:'人資部',jobTitle:'人資專員',noticeDays:30,actualNoticeDate:'民國115年10月01日',legalBasis:'勞動基準法第11條第5款',reasonDetail:'勞工對於所擔任之工作確不能勝任',startDate:'民國107年07月03日',tenureDays:3043,endDate:'民國115年10月31日',settlementDate:'民國115年11月05日',averageWage:74947,severance:312176,noticePay:74947};

(async()=>{
  const checks=[];
  const check=(label,condition)=>{assert.ok(condition,label);checks.push(label)};
  check('中文姓名檔名正確',NoticeExcel.fileName('王小明')==='王小明-資遣通知書.xlsx');
  check('空白姓名不出現 undefined/null',NoticeExcel.fileName('')==='資遣通知書.xlsx');
  const sheet=NoticeExcel.buildSheet(model);
  check('公司名稱存在',sheet.includes(model.companyName));
  check('文件標題存在',sheet.includes('員 工 資 遣 通 知 書'));
  check('員工資料區存在',sheet.includes('一、員工資料'));
  check('資遣資料區存在',sheet.includes('二、資遣資料'));
  check('資遣費金額區存在',sheet.includes('三、資遣費金額'));
  check('員工核心資料正確',sheet.includes(model.employeeId)&&sheet.includes(model.employeeAddress)&&sheet.includes(model.employeePhone));
  check('日期與年資正確',sheet.includes(model.actualNoticeDate)&&sheet.includes(model.startDate)&&sheet.includes(model.endDate)&&sheet.includes('3043日'));
  check('法源與理由正確',sheet.includes(model.legalBasis)&&sheet.includes(model.reasonDetail));
  check('平均工資為正式結果',sheet.includes('<v>74947</v>'));
  check('資遣費為正式結果',sheet.includes('<v>312176</v>'));
  check('預告工資為正式結果',sheet.includes('<v>74947</v>'));
  check('最終金額只使用簡單加總公式',sheet.includes('<f>F16+B17</f>')&&sheet.includes('<v>387123</v>'));
  check('說明文字存在',sheet.includes('離職同仁應遵守保密協定'));
  check('簽名與日期區存在',sheet.includes('員工簽名：')&&sheet.includes('日期：'));
  check('A4直式列印',sheet.includes('paperSize="9" orientation="portrait"'));
  check('列印一頁寬一頁高',sheet.includes('fitToWidth="1" fitToHeight="1"'));
  check('水平置中列印',sheet.includes('horizontalCentered="1"'));
  check('合併儲存格包含主要區塊',sheet.includes('ref="A5:H5"')&&sheet.includes('ref="B11:H11"')&&sheet.includes('ref="A19:H19"'));
  const bytes=await NoticeExcel.createWorkbook(model,{type:'nodebuffer'});
  fs.mkdirSync(outputDir,{recursive:true});fs.writeFileSync(outputPath,bytes);
  const zip=await JSZip.loadAsync(bytes);
  check('XLSX核心檔案完整',!!zip.file('[Content_Types].xml')&&!!zip.file('xl/workbook.xml')&&!!zip.file('xl/styles.xml')&&!!zip.file('xl/worksheets/sheet1.xml'));
  const workbook=await zip.file('xl/workbook.xml').async('string');
  const styles=await zip.file('xl/styles.xml').async('string');
  check('工作表名稱正確',workbook.includes('<sheet name="資遣通知書"'));
  check('列印範圍固定為單頁內容',workbook.includes("'資遣通知書'!$A$1:$H$21"));
  check('框線與簽名線樣式存在',styles.includes('<borders count="4">')&&styles.includes('<bottom style="thin">'));
  check('金額使用數字格式',styles.includes('formatCode="#,##0&quot; 元&quot;"'));
  const app=fs.readFileSync(path.resolve(__dirname,'..','app.js'),'utf8');
  check('正式UI加入資遣通知書Excel按鈕',app.includes('installNoticeExcelUI()')&&app.includes("button.dataset.noticeExcel=''"));
  check('沒有改變資遣通知書PDF事件',app.includes("type==='notice'?noticePdf(latest)"));
  console.log(`PASS ${checks.length}/${checks.length}`);
  for(const label of checks)console.log(`PASS - ${label}`);
  console.log(`OUTPUT ${outputPath}`);
})().catch(error=>{console.error(error);process.exit(1)});
